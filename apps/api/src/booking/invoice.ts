import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import type { VenueBookingSummary } from '@quartermaster/shared';

// "IDR 19,300,000" or "USD 1,234.56": the venue currencies' minor units differ, so IDR has none.
export function formatAmount(amountMinor: number, currency: string): string {
  const major = currency === 'IDR' ? amountMinor : amountMinor / 100;
  const digits = currency === 'IDR' ? 0 : 2;
  return `${currency} ${major.toLocaleString('en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits })}`;
}

export const invoiceNumber = (threadId: string) => `INV-${threadId.slice(0, 8).toUpperCase()}`;

export interface VenueInvoiceInput {
  threadId: string;
  summary: VenueBookingSummary;
  reference: string;
  paidAt: Date;
}

// The paid venue plan as a one-page A4 invoice, drawn from our own records (never from the browser or the agent).
export async function venueInvoicePdf({
  threadId,
  summary,
  reference,
  paidAt,
}: VenueInvoiceInput): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([595, 842]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.1, 0.1, 0.12);
  const grey = rgb(0.4, 0.4, 0.45);
  const left = 50;
  const right = 545;
  let y = 790;

  const text = (s: string, x: number, size = 10, f = font, color = ink) =>
    page.drawText(s, { x, y, size, font: f, color });
  const rightText = (s: string, size = 10, f = font) =>
    page.drawText(s, { x: right - f.widthOfTextAtSize(s, size), y, size, font: f, color: ink });
  const row = (label: string, value: string) => {
    text(label, left, 10, bold, grey);
    text(value, left + 110, 10);
    y -= 18;
  };

  const { event, venue, estimate, fx, payable } = summary;

  text('Invoice', left, 26, bold);
  rightText('PAID', 18, bold);
  y -= 26;
  text(invoiceNumber(threadId), left, 11, font, grey);
  y -= 34;

  text('Event', left, 12, bold);
  y -= 20;
  row('Name', event.name);
  row('Date', event.date.slice(0, 10));
  row('People', String(event.headcount));
  y -= 10;

  text('Vendor', left, 12, bold);
  y -= 20;
  row('Venue', venue.name);
  row('Area', venue.area);
  y -= 10;

  text('One day at the venue', left, 12, bold);
  y -= 22;
  for (const line of estimate.lines) {
    text(line.label, left);
    rightText(formatAmount(line.amountMinor, estimate.currency));
    y -= 18;
  }
  page.drawLine({ start: { x: left, y: y + 8 }, end: { x: right, y: y + 8 }, thickness: 0.5, color: grey });
  y -= 4;
  text('One-day estimate', left, 10, bold);
  rightText(formatAmount(estimate.total, estimate.currency), 10, bold);
  y -= 18;
  text('Demo exchange rate', left, 10, font, grey);
  rightText(`1 USD = ${formatAmount(fx.localMinorPerUsd, fx.from)}`);
  y -= 30;

  text('Total paid', left, 14, bold);
  rightText(formatAmount(payable.amountMinor, payable.currency), 14, bold);
  y -= 34;

  text('Payment', left, 12, bold);
  y -= 20;
  row('Method', 'PayPal (sandbox)');
  row('Reference', reference);
  row('Paid on', paidAt.toISOString().slice(0, 10));

  y = 60;
  text('Generated by Leonid from its own payment records. Sandbox demo, not a tax document.', left, 8, font, grey);

  return pdf.save();
}
